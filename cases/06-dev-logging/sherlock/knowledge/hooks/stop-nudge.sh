#!/usr/bin/env bash
# НЕОБЯЗАТЕЛЬНОЕ усиление цикла самообучения. Событие Stop.
#
# Основной путь — шаг 7 в SKILL.md: агент сам предлагает карточку в конце
# расследования. Этот хук ничего не делает сам, он только НАПОМИНАЕТ, если
# расследование закончилось, а карточку не предложили и не объяснили почему.
#
# Свойства, без которых он не имеет права существовать:
#   * ничего не пишет в базу знаний — только печатает строку;
#   * всегда exit 0: сессия не должна падать из-за напоминалки;
#   * хуки выключены, не поддерживаются или скрипт не запустился —
#     основной путь работает без изменений (R1, graceful degradation).
#
# Подключение (frontmatter SKILL.md — Qwen Coder подставляет QWEN_SKILL_ROOT):
#
#   hooks:
#     Stop:
#       - hooks:
#           - type: command
#             command: "$QWEN_SKILL_ROOT/knowledge/hooks/stop-nudge.sh"
#
set -u

ROOT="${QWEN_SKILL_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
KB="$ROOT/knowledge/patterns"

CARDS=0
[ -d "$KB" ] && CARDS=$(find "$KB" -maxdepth 1 -name '*.md' 2>/dev/null | wc -l | tr -d ' ')

cat <<EOF
[sherlock/knowledge] Сессия завершается. Карточек в базе: $CARDS.
  Проверьте, что в ответе есть строка «ЗНАНИЯ: …» — что прочитано, что применено,
  что предложено (или почему нечего предлагать).
  Если инцидент узнаётся по конкретной подписи и такой карточки ещё нет —
  предложите её (шаг 7). Ничего не сохраняется без вашего «да».
EOF

exit 0
